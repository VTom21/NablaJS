

export function PI(digits = 6) : number{
    const pi = "3.141592653589793"
    let value = "" 
    let counter = 0;
    for(var i = 0; counter < digits; i++){
        if(pi[i] !== "."){
            counter++;
        }
        value += pi[i]
    }

    

    return parseFloat(value)
}

